#!/usr/bin/env node
// Regenerates server/analytics/world-map.js — the country outlines the
// analytics dashboard colours in. Only needed if the map itself should
// change (projection, detail level); the output is committed.
//
// Usage (d3-geo is the only dependency, install it anywhere outside the repo):
//   npm install d3-geo@3
//   B=https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson
//   curl -LO $B/ne_110m_admin_0_countries.geojson
//   curl -LO $B/ne_50m_admin_0_countries.geojson
//   node build-world-map.mjs ne_110m_admin_0_countries.geojson \
//        ne_50m_admin_0_countries.geojson ../server/analytics/world-map.js
//
// Outlines come from the coarse 1:110m set (small file). Every country
// also gets a point — where the dashboard puts its device-count bubble —
// including the ones too small to have an outline there (Singapore,
// Hong Kong, Malta…), whose position is taken from the 1:50m set.

import { readFileSync, writeFileSync } from 'node:fs';
import { geoEqualEarth, geoPath } from 'd3-geo';

const [coarsePath, finePath, outPath] = process.argv.slice(2);
if (!outPath) {
  console.error('usage: build-world-map.mjs <110m.geojson> <50m.geojson> <out.js>');
  process.exit(1);
}

const WIDTH = 2000;            // viewBox units; integer coordinates at this size are sub-pixel on screen
const MIN_ISLAND_AREA = 6;     // drop islands smaller than this (viewBox units²) from multi-part countries

const load = (p) => JSON.parse(readFileSync(p, 'utf8')).features;
const code = (f) => (/^[A-Z]{2}$/.test(f.properties.ISO_A2_EH) ? f.properties.ISO_A2_EH : null);

const coarse = load(coarsePath).filter((f) => code(f) !== 'AQ');
const fine = load(finePath).filter((f) => code(f) !== 'AQ');

const projection = geoEqualEarth().fitWidth(WIDTH, { type: 'FeatureCollection', features: coarse });
const path = geoPath(projection).digits(0);
const height = Math.ceil(path.bounds({ type: 'FeatureCollection', features: coarse })[1][1]);

/** Absolute "M…L…Z" from d3 → one relative path, minus zero-length steps and speck islands. */
function compact(d) {
  const rings = d.split('M').filter(Boolean).map((ring) =>
    ring.replace(/Z$/, '').split('L').map((pair) => pair.split(',').map(Number)));
  const area = (ring) => Math.abs(ring.reduce((sum, [x, y], i) => {
    const [nx, ny] = ring[(i + 1) % ring.length];
    return sum + (x * ny - nx * y);
  }, 0)) / 2;
  const largest = Math.max(...rings.map(area));
  return rings
    .filter((ring) => area(ring) >= Math.min(MIN_ISLAND_AREA, largest))
    .map((ring) => {
      let [px, py] = ring[0];
      let out = `M${px},${py}l`;
      let first = true;
      for (const [x, y] of ring.slice(1)) {
        const dx = x - px, dy = y - py;
        if (dx === 0 && dy === 0) continue;
        out += (first || dx < 0 ? '' : ' ') + dx + (dy < 0 ? '' : ' ') + dy;
        first = false;
        px = x; py = y;
      }
      return out + 'z';
    })
    .join('');
}

/** Centre of a country's biggest landmass — so Alaska doesn't drag the US bubble into Canada, or Guiana France's into the Atlantic. */
function anchor(f) {
  const parts = f.geometry.type === 'MultiPolygon'
    ? f.geometry.coordinates.map((coordinates) => ({ type: 'Polygon', coordinates }))
    : [f.geometry];
  const main = parts.reduce((a, b) => (path.area(b) > path.area(a) ? b : a));
  return path.centroid(main).map(Math.round);
}

const shapes = {};
const points = {};
let unnamed = 0;
for (const f of coarse) {
  const d = path(f);
  if (!d) continue;
  // Territories with no ISO code (N. Cyprus, Somaliland) are still land:
  // keep them under a "_n" key so the map has no holes, just no data.
  const key = code(f) ?? `_${++unnamed}`;
  shapes[key] = (shapes[key] ?? '') + compact(d);
  if (code(f)) points[key] = anchor(f);
}
for (const f of fine) {
  const key = code(f);
  if (!key || points[key]) continue;
  const [x, y] = anchor(f);
  if (Number.isFinite(x) && Number.isFinite(y)) points[key] = [x, y];
}

const banner = `/* Generated by scripts/build-world-map.mjs — do not edit by hand.
 * Country outlines for dashboard.php, keyed by ISO 3166-1 alpha-2.
 * Made with Natural Earth (public domain), Equal Earth projection. */
`;
writeFileSync(outPath, `${banner}window.DASH_WORLD_MAP = ${JSON.stringify({ w: WIDTH, h: height, shapes, points })};\n`);
console.log(`${Object.keys(shapes).length} shapes, ${Object.keys(points).length} points, ${height} high → ${outPath}`);
